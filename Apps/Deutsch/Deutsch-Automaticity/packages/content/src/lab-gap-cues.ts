/** The cued exercise for a Lab cloze, keeping the instruction before the sentence. */
export function labGapCueFor(
  title: string,
  exercise: number,
  prompt: string,
):
  | { readonly prompt: string; readonly answers?: readonly string[] }
  | undefined {
  // A later row for the same exercise replaces an earlier one.
  const row = LAB_GAP_CUES.findLast(
    ([name, index]) => name === title && index === exercise,
  );
  if (!row) return undefined;
  const [, , sentence, ...answers] = row;
  // The instruction ends at its first colon; the sentence may contain more.
  const cued = `${prompt.slice(0, prompt.indexOf(":") + 1)} ${sentence}`;
  return answers.length ? { prompt: cued, answers } : { prompt: cued };
}
